-- --------------------------------------------------------
-- Tabella per il catalogo delle squadre (Club, Nazionali, NBA)
-- --------------------------------------------------------
CREATE TABLE IF NOT EXISTS teams (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL UNIQUE,
  categoria TEXT NOT NULL,
  sezione TEXT NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

-- --------------------------------------------------------
-- Tabella per la registrazione degli ordini
-- --------------------------------------------------------
CREATE TABLE IF NOT EXISTS orders (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  data TEXT NOT NULL UNIQUE,
  nome TEXT NOT NULL,
  telefono TEXT NOT NULL,
  squadra TEXT NOT NULL,
  personalizzazione TEXT,
  taglia TEXT,
  totale TEXT NOT NULL,
  foto TEXT,
  prezzo_fornitore TEXT,
  costo_prodotti_usd TEXT,
  costo_spedizione_usd TEXT,
  costo_totale_usd TEXT,
  cambio_usd_eur TEXT,
  costo_totale_eur TEXT,
  profitto_eur TEXT,
  is_archived BOOLEAN DEFAULT FALSE,
  lotto_id INT DEFAULT NULL,
  carrello JSONB DEFAULT '[]'::jsonb,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

-- Aggiungi vincolo di chiave esterna tra orders e lotti per garantire l'integrità dei dati
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 
        FROM pg_constraint 
        WHERE conname = 'fk_orders_lotto_id'
    ) THEN
        ALTER TABLE orders 
        ADD CONSTRAINT fk_orders_lotto_id 
        FOREIGN KEY (lotto_id) 
        REFERENCES lotti(id) 
        ON DELETE CASCADE;
    END IF;
END $$;

CREATE INDEX IF NOT EXISTS idx_orders_data ON orders(data);
CREATE INDEX IF NOT EXISTS idx_orders_lotto_id ON orders(lotto_id);

-- --------------------------------------------------------
