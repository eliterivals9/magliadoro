CREATE TABLE IF NOT EXISTS profit_shares (
  id BIGSERIAL PRIMARY KEY,
  order_id TEXT UNIQUE NOT NULL,
  profit_total NUMERIC(10, 2) NOT NULL DEFAULT 0,
  sergio_percentage NUMERIC(5, 2) NOT NULL DEFAULT 50,
  riccardo_percentage NUMERIC(5, 2) NOT NULL DEFAULT 50,
  sergio_initial_share NUMERIC(10, 2) NOT NULL DEFAULT 0,
  riccardo_initial_share NUMERIC(10, 2) NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS profit_share_movements (
  id BIGSERIAL PRIMARY KEY,
  profit_share_id TEXT NOT NULL,
  order_id TEXT NOT NULL,
  recipient TEXT NOT NULL CHECK (recipient IN ('sergio', 'riccardo', 'shared')),
  type TEXT NOT NULL DEFAULT 'completino',
  amount NUMERIC(10, 2) NOT NULL,
  sergio_amount NUMERIC(10, 2) NOT NULL DEFAULT 0,
  riccardo_amount NUMERIC(10, 2) NOT NULL DEFAULT 0,
  description TEXT,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

ALTER TABLE profit_shares ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Consenti tutto profit_shares" ON profit_shares FOR ALL USING (true) WITH CHECK (true);

ALTER TABLE profit_share_movements ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Consenti tutto profit_share_movements" ON profit_share_movements FOR ALL USING (true) WITH CHECK (true);
