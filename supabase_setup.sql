-- --------------------------------------------------------
-- Tabella per la Wishlist dei clienti
-- --------------------------------------------------------
CREATE TABLE IF NOT EXISTS customer_wishlist (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID NOT NULL,
  product_id TEXT NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL,
  CONSTRAINT unique_user_product UNIQUE(user_id, product_id)
);

-- Abilita Row Level Security (RLS) per sicurezza
ALTER TABLE customer_wishlist ENABLE ROW LEVEL SECURITY;

-- Criteri di accesso RLS per la Wishlist
CREATE POLICY "Gli utenti possono gestire la propria wishlist" ON customer_wishlist
  FOR ALL TO authenticated USING (auth.uid() = user_id) WITH CHECK (auth.uid() = user_id);


-- --------------------------------------------------------
-- Tabella per le conversazioni della chat di assistenza
-- --------------------------------------------------------
CREATE TABLE IF NOT EXISTS chat_conversations (
  id UUID DEFAULT gen_random_uuid() PRIMARY KEY,
  user_id UUID UNIQUE,
  nome TEXT,
  email TEXT,
  stato TEXT DEFAULT 'Nuova',
  created_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL,
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL,
  last_message_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

-- --------------------------------------------------------
-- Tabella per i messaggi della chat di assistenza
-- --------------------------------------------------------
CREATE TABLE IF NOT EXISTS chat_messages (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  conversation_id UUID REFERENCES chat_conversations(id) ON DELETE CASCADE,
  sender TEXT NOT NULL,
  message TEXT,
  attachment_url TEXT,
  attachment_type TEXT,
  is_read BOOLEAN DEFAULT FALSE,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);


