-- --------------------------------------------------------
-- Tabella per le Recensioni dei Clienti (Verificate ed Esperienze Condivise)
-- --------------------------------------------------------
CREATE TABLE IF NOT EXISTS reviews (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id UUID DEFAULT NULL,
  customer_name TEXT NOT NULL,
  email TEXT DEFAULT NULL,
  order_id BIGINT DEFAULT NULL,
  order_number TEXT DEFAULT NULL,
  product_id TEXT DEFAULT NULL,
  product_name TEXT DEFAULT NULL,
  product_image TEXT DEFAULT NULL,
  purchase_date TEXT DEFAULT NULL,
  rating INT NOT NULL CHECK (rating >= 1 AND rating <= 5),
  title TEXT DEFAULT NULL,
  comment TEXT NOT NULL,
  images JSONB DEFAULT '[]'::jsonb,
  status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'approved', 'rejected')),
  review_type TEXT NOT NULL DEFAULT 'shared_experience' CHECK (review_type IN ('verified_purchase', 'shared_experience')),
  created_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_reviews_status ON reviews(status);
CREATE INDEX IF NOT EXISTS idx_reviews_created_at ON reviews(created_at DESC);
CREATE INDEX IF NOT EXISTS idx_reviews_product_id ON reviews(product_id);

-- Policy RLS per recensioni
ALTER TABLE reviews ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Consenti lettura recensioni approvate" ON reviews FOR SELECT USING (true);
CREATE POLICY "Consenti inserimento recensioni" ON reviews FOR INSERT WITH CHECK (true);
CREATE POLICY "Consenti modifica recensioni" ON reviews FOR UPDATE USING (true);
CREATE POLICY "Consenti eliminazione recensioni" ON reviews FOR DELETE USING (true);

-- --------------------------------------------------------
-- Bucket Storage 'reviews' per le Foto delle Recensioni
-- (Eseguire nella SQL Editor di Supabase per abilitare il bucket 'reviews')
-- --------------------------------------------------------
INSERT INTO storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
VALUES ('reviews', 'reviews', true, 5242880, ARRAY['image/png', 'image/jpeg', 'image/webp', 'image/gif'])
ON CONFLICT (id) DO UPDATE SET public = true;

-- Policy RLS per il bucket storage 'reviews'
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_policies WHERE schemaname = 'storage' AND tablename = 'objects' AND policyname = 'Foto recensioni pubbliche in lettura'
  ) THEN
    CREATE POLICY "Foto recensioni pubbliche in lettura" ON storage.objects FOR SELECT USING (bucket_id = 'reviews');
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_policies WHERE schemaname = 'storage' AND tablename = 'objects' AND policyname = 'Consenti upload foto recensioni'
  ) THEN
    CREATE POLICY "Consenti upload foto recensioni" ON storage.objects FOR INSERT WITH CHECK (bucket_id = 'reviews');
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_policies WHERE schemaname = 'storage' AND tablename = 'objects' AND policyname = 'Consenti modifica foto recensioni'
  ) THEN
    CREATE POLICY "Consenti modifica foto recensioni" ON storage.objects FOR UPDATE USING (bucket_id = 'reviews');
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_policies WHERE schemaname = 'storage' AND tablename = 'objects' AND policyname = 'Consenti eliminazione foto recensioni'
  ) THEN
    CREATE POLICY "Consenti eliminazione foto recensioni" ON storage.objects FOR DELETE USING (bucket_id = 'reviews');
  END IF;
END $$;

